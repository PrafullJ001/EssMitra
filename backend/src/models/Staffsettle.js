const mongoose = require('mongoose');

const settlementSchema = new mongoose.Schema(
  {
    // Not tied to a specific expense — a running adjustment against the
    // staff member's overall advance total.
    staffMember: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: true,
    },

    amount: {
      type: Number,
      required: true,
      min: 0,
    },

    date: {
      type: Date,
      default: Date.now,
    },

    note: {
      type: String,
      trim: true,
      default: '',
    },

    createdBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: true,
    },
  },
  { timestamps: true }
);

module.exports = mongoose.model('Settlement', settlementSchema);